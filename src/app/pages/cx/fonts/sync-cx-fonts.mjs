/**
 * Copies subset woff2 files from @fontsource into src/assets/cx/fonts
 * and generates deferred @font-face CSS (latin + devanagari for Noto).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '../../../../../');
const assetsDir = path.join(root, 'src/assets/cx/fonts');
const assetsCss = path.join(root, 'src/assets/cx/cx-font-faces-deferred.css');
const nodeModules = path.join(root, 'node_modules/@fontsource');

const copies = [
  ['bricolage-grotesque', 'bricolage-grotesque-latin-{w}-normal.woff2', [400, 500, 600, 800]],
  ['instrument-sans', 'instrument-sans-latin-{w}-normal.woff2', [400, 500, 600, 700]],
  ['ibm-plex-mono', 'ibm-plex-mono-latin-{w}-normal.woff2', [400, 500, 600, 700]],
  [
    'noto-sans-devanagari',
    'noto-sans-devanagari-devanagari-{w}-normal.woff2',
    [400, 500, 600, 800]
  ]
];

const familyNames = {
  'bricolage-grotesque': 'Bricolage Grotesque',
  'instrument-sans': 'Instrument Sans',
  'ibm-plex-mono': 'IBM Plex Mono',
  'noto-sans-devanagari': 'Noto Sans Devanagari'
};

/** Map design weight 800 to 700 files where the family has no 800 cut. */
function resolveWeight(pkg, weight) {
  if (weight === 800 && (pkg === 'instrument-sans' || pkg === 'ibm-plex-mono')) {
    return 700;
  }
  return weight;
}

function copyFonts() {
  fs.mkdirSync(assetsDir, { recursive: true });

  for (const [pkg, pattern, weights] of copies) {
    const srcDir = path.join(nodeModules, pkg, 'files');
    for (const w of weights) {
      const fileWeight = resolveWeight(pkg, w);
      const fileName = pattern.replace('{w}', String(fileWeight));
      const src = path.join(srcDir, fileName);
      if (!fs.existsSync(src)) {
        throw new Error(`Missing font file: ${src}`);
      }
      const destName =
        w === fileWeight ? fileName : fileName.replace(`-${fileWeight}-`, `-${w}-`);
      fs.copyFileSync(src, path.join(assetsDir, destName));
    }
  }
}

function fontFace(family, weight, fileName) {
  return `@font-face {
  font-family: '${family}';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url('/assets/cx/fonts/${fileName}') format('woff2');
}
`;
}

function buildDeferredCss() {
  let css = '/* Generated by sync-cx-fonts.mjs — do not edit */\n';

  for (const [pkg, pattern, weights] of copies) {
    const family = familyNames[pkg];
    for (const w of weights) {
      const fileWeight = resolveWeight(pkg, w);
      const fileName = pattern.replace('{w}', String(fileWeight));
      const storedName =
        w === fileWeight ? fileName : fileName.replace(`-${fileWeight}-`, `-${w}-`);
      css += fontFace(family, w, storedName);
    }
  }

  fs.mkdirSync(path.dirname(assetsCss), { recursive: true });
  fs.writeFileSync(assetsCss, css);
}

copyFonts();
buildDeferredCss();
console.log('CX fonts synced to src/assets/cx/fonts');
